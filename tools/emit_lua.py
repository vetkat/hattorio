"""Emit Lua data files for the tiling core.

WHY DOUBLES, NOT EXACT INTEGERS
-------------------------------
An earlier design stored the rules as exact integers in Z[phi][sqrt3]. That
was a mistake. It came from confusing two different things.

The desync risk in Factorio is `math.sin`, `math.cos` and `pow`, because their
libm implementations really are different on different platforms. But
IEEE-754 requires CORRECT ROUNDING for + - * / and sqrt, so they give the same
bits everywhere. The Lua interpreter runs each operation as a separate VM
instruction, so no compiler can contract two of them into an FMA. Factorio
runs on 64-bit x86 and ARM processors, which do double arithmetic without the
80-bit excess precision of x87. Here,
doubles are exactly as deterministic as integers. They are only less
accurate, and the measurements show that this does not matter:

    depth  coverage      relative error   absolute error
      8      26,660 t      5.7e-16          8e-12 tiles
     10     183,419 t      4.3e-16          7e-11 tiles
     12   1,194,588 t      5.3e-16          4e-10 tiles

The relative error stays at machine epsilon and does not grow with depth.
Depth 12 covers the whole Factorio map with an error of four ten-billionths of
a tile.

Exact integers could not go past depth 4. The numerators of the level-6 rules
are 1.4e14, so one composition makes a raw product near 1e28, far past 2^53.
Cross-reduction cannot help: the gcd of the operands is 1, because the
cancellation is additive and not multiplicative.

The exact arithmetic stays where it belongs: offline, in this pipeline, where
it derives the rules and proves them correct. Only the VALUES ship.
"""
from __future__ import annotations

import math
import pathlib

from tools.field import K
from tools.geometry import HAT_OUTLINE
from tools.substitution import levels
from tools.verify import verify_all

# Coverage grows linearly with the hat size, so the SMALLEST allowed size sets
# the depth to emit. At size 15 (the minimum setting), depth 12 reaches the
# edge of the map. 15 leaves a margin. Doubles have no
# coefficient limit, so each extra level costs only a few hundred bytes.
MAX_LEVEL = 15
ROOT = pathlib.Path(__file__).resolve().parents[1]
HEADER = "-- GENERATED by `tools/emit_lua.py`. DO NOT EDIT.\n"

PHI = (1 + math.sqrt(5)) / 2
SQRT3 = math.sqrt(3)


def _f(k: K) -> float:
    """Exact ring element -> the double that Lua will hold. Rounded only once."""
    return k.to_float()


def _num(v: float) -> str:
    """%.17g round-trips a double exactly."""
    return "%.17g" % v


def _hat_circumradius() -> float:
    return max(math.hypot(*p.to_float()) for p in HAT_OUTLINE)


def _prune_radius(mt) -> float:
    """The radius that bounds the whole SUBTREE of hats of a metatile.

    This adds two corrections to the plain outline radius. Without them, the
    descent would lose hats with no error:

    * Hats cross metatile boundaries, so the outline does not contain them.
      Allow an overhang of one full hat diameter.
    * construct_metatiles makes the outlines GROW at each level. So this value
      is per level, and it is never a constant.
    """
    worst = max(math.hypot(*p.to_float()) for p in mt.outline)
    return worst + 2.0 * _hat_circumradius()


def _hat_scale(lv) -> float:
    """Uniform scale of the level-0 hat placements.

    H_init and the related functions place hats at half scale. So a descent at
    `unit` tiles per kite unit gives hats with a circumradius of
    0.5 * unit * circumradius. The pipeline emits the value, so callers do not
    need to know this. The check for a uniform scale finds any placement that
    breaks congruence.
    """
    scales = set()
    for mt in lv[0].values():
        for ch in mt.children:
            d = ch.xf.det().to_float()
            scales.add(round(math.sqrt(abs(d)), 12))
    assert len(scales) == 1, f"hat placements are not congruent: {scales}"
    return scales.pop()


def emit_rules(path):
    lv = levels(MAX_LEVEL)
    out = [HEADER, "return {\n  max_level = %d,\n  hat_scale = %s,\n  levels = {\n"
           % (MAX_LEVEL, _num(_hat_scale(lv)))]
    for i, shapes in enumerate(lv):
        out.append("    [%d] = {\n" % i)
        for name in ("H", "T", "P", "F"):
            out.append("      %s = {\n" % name)
            for ch in shapes[name].children:
                label = ch.geom if isinstance(ch.geom, str) else ch.geom.label
                vals = ", ".join(_num(_f(k)) for k in ch.xf.m)
                out.append('        { shape = "%s", xf = { %s } },\n' % (label, vals))
            out.append("      },\n")
        out.append("    },\n")
    out.append("  },\n  radius = {\n")
    for i, shapes in enumerate(lv):
        rad = ", ".join("%s = %s" % (n, _num(_prune_radius(shapes[n]) * 1.05))
                        for n in ("H", "T", "P", "F"))
        out.append("    [%d] = { %s },\n" % (i, rad))
    out.append("  },\n}\n")
    path.write_text("".join(out))


def emit_geometry(path):
    pts = ",\n    ".join("{ %s, %s }" % (_num(x), _num(y))
                         for x, y in (p.to_float() for p in HAT_OUTLINE))
    path.write_text(HEADER + "return {\n  vertices = %d,\n  circumradius = %s,\n"
                    "  outline = {\n    %s\n  },\n}\n"
                    % (len(HAT_OUTLINE), _num(_hat_circumradius()), pts))


def main():
    errs = verify_all(2)
    if errs:
        raise SystemExit("verification failed:\n" + "\n".join(errs))
    (ROOT / "data").mkdir(exist_ok=True)
    emit_rules(ROOT / "data" / "hat_rules.lua")
    emit_geometry(ROOT / "data" / "hat_geometry.lua")
    print(f"wrote data/hat_rules.lua (levels 0..{MAX_LEVEL}) and data/hat_geometry.lua")


if __name__ == "__main__":
    main()
