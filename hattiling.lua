local RULES = {
  H = {
    -- { "H", <affine> }, { "H", <affine> }, { "H", <affine> },
    -- { "T", <affine> },
    -- { "F", <affine> }, { "F", <affine> }, { "F", <affine> },
  },
  T = {
    -- { "H", <affine> },
  },
  P = {},
  F = {},
}

-- Circumradius of each level-0 metatile about its own origin, in the same
-- kite-grid units as HAT_OUTLINE. Fill in once METATILE is populated; these
-- only need to be upper bounds, and being generous just costs a little pruning.
local METATILE_RADIUS = {
  H = 4 * HAT_RADIUS,
  T = 2 * HAT_RADIUS,
  P = 3 * HAT_RADIUS,
  F = 3 * HAT_RADIUS,
}

--------------------------------------------------------------------------------
-- Lazy traversal
--
-- Walks the supertile tree from the root, emitting only hats that could touch
-- the query box. Cost is proportional to the output, not to the tiling size.
--------------------------------------------------------------------------------

local function circle_misses_box(cx, cy, r, box)
  -- Distance from circle centre to the axis-aligned box.
  local dx = math.max(box.left - cx, 0, cx - box.right)
  local dy = math.max(box.top  - cy, 0, cy - box.bottom)
  return dx*dx + dy*dy > r*r
end

-- shape: "H" | "T" | "P" | "F"
-- xform: accumulated transform from this node's frame to world space
-- level: remaining substitution depth (0 = expand into hats)
-- box:   {left, top, right, bottom} in world space
-- out:   accumulator
local function descend(shape, xform, level, box, out)
  local k  = scale_of(xform)
  local cx, cy = apply(xform, 0, 0)
  local r  = METATILE_RADIUS[shape] * k * (INFLATE ^ level)

  if circle_misses_box(cx, cy, r, box) then return end

  if level == 0 then
    for _, hat in ipairs(METATILE[shape]) do
      local hx = mul(xform, hat.xform)
      local px, py = apply(hx, 0, 0)
      if not circle_misses_box(px, py, HAT_RADIUS * scale_of(hx), box) then
        out[#out+1] = { xform = hx, reflected = hat.reflected }
      end
    end
    return
  end

  for _, child in ipairs(RULES[shape]) do
    descend(child[1], mul(xform, child[2]), level - 1, box, out)
  end
end

