--------------------------------------------------------------------------------
-- hat_tiling.lua
--
-- Lazy, deterministic generator for the "hat" aperiodic monotile tiling
-- (Smith, Myers, Kaplan & Goodman-Strauss, 2023), shaped for use inside a
-- Factorio mod.
--
-- Design:
--   * The tiling is defined by a substitution system on four metatiles
--     H, T, P, F with inflation factor phi^2 in length (phi^4 in area).
--   * Rather than materialising the whole tiling, we keep only a root
--     supertile and recurse down it per chunk, pruning branches whose
--     bounding circle cannot intersect the chunk.
--   * Fully deterministic: no RNG, so multiplayer-safe with no state to sync.
--
-- TWO THINGS YOU MUST FILL IN (marked TODO below):
--   1. RULES       - the substitution geometry
--   2. METATILE    - the hat placements inside each level-0 metatile
--
-- Do NOT try to re-derive these from the figures in the paper. Craig Kaplan's
-- reference implementation (hatviz, github.com/isohedral/hatviz) contains them
-- as explicit transformation matrices; port those, and check its licence
-- before shipping.
--------------------------------------------------------------------------------

local M = {}

local PHI      = (1 + math.sqrt(5)) / 2
local INFLATE  = PHI * PHI            -- ~2.618, length scale per level
local SQRT3    = math.sqrt(3)

--------------------------------------------------------------------------------
-- Affine transforms, stored as a flat 6-tuple:
--   {a, b, c,
--    d, e, f}   maps (x, y) -> (a*x + b*y + c, d*x + e*y + f)
--------------------------------------------------------------------------------

local IDENTITY = {1, 0, 0, 0, 1, 0}

local function mul(A, B)
  return {
    A[1]*B[1] + A[2]*B[4],  A[1]*B[2] + A[2]*B[5],  A[1]*B[3] + A[2]*B[6] + A[3],
    A[4]*B[1] + A[5]*B[4],  A[4]*B[2] + A[5]*B[5],  A[4]*B[3] + A[5]*B[6] + A[6],
  }
end

local function apply(A, x, y)
  return A[1]*x + A[2]*y + A[3],
         A[4]*x + A[5]*y + A[6]
end

-- Uniform scale factor of a transform. The substitution uses only rotations,
-- reflections and uniform scaling, so this is well defined.
local function scale_of(A)
  return math.sqrt(math.abs(A[1]*A[5] - A[2]*A[4]))
end

local function rot(theta)
  local c, s = math.cos(theta), math.sin(theta)
  return {c, -s, 0, s, c, 0}
end

local function translate(x, y)  return {1, 0, x, 0, 1, y} end
local function scale(k)         return {k, 0, 0, 0, k, 0} end
local function reflect_x()      return {-1, 0, 0, 0, 1, 0} end

--------------------------------------------------------------------------------
-- 1. Hat outline, in kite-grid units.
--
-- The hat is eight kites of the [3.4.6.4] Laves tiling, so every vertex sits
-- on a lattice generated by 1.5 and sqrt(3)/2. VERIFY these coordinates against
-- hatviz before trusting them; the winding and starting vertex matter for the
-- point-in-polygon test below.
--------------------------------------------------------------------------------

local HAT_OUTLINE = {
  {  0.0,  0.0        },
  { -1.5, -0.5*SQRT3  },
  {  0.0, -1.0*SQRT3  },
  {  1.5, -0.5*SQRT3  },
  {  3.0, -1.0*SQRT3  },
  {  4.5, -0.5*SQRT3  },
  {  3.0,  0.0        },
  {  3.0,  1.0*SQRT3  },
  {  1.5,  1.5*SQRT3  },
  {  0.0,  1.0*SQRT3  },
  {  0.0,  2.0*SQRT3  },
  { -1.5,  2.5*SQRT3  },
  { -3.0,  2.0*SQRT3  },
  { -3.0,  1.0*SQRT3  },
}

-- Conservative circumradius of the outline about its own origin.
local HAT_RADIUS = (function()
  local r = 0
  for _, p in ipairs(HAT_OUTLINE) do
    r = math.max(r, math.sqrt(p[1]*p[1] + p[2]*p[2]))
  end
  return r
end)()

