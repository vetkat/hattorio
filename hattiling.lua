-- Public API
--------------------------------------------------------------------------------

-- Tiles per kite-grid unit. Pick this so one hat spans roughly 16-24 Factorio
-- tiles: smaller and the square-tile rasterisation looks like noise, larger and
-- the aperiodicity stops being visible at play scale.
M.UNIT = 4.0

-- Depth of the root supertile. Each level multiplies covered area by ~6.854.
-- Level 8 from an H root covers a very large map; raise it if players reach the
-- edge, since nothing is precomputed and the cost is only in the descent.
M.LEVELS = 8

M.root_shape = "H"

local function root_xform()
  return mul(translate(0, 0), scale(M.UNIT))
end

--- Returns the hats overlapping an axis-aligned world-space box.
-- @param box {left=, top=, right=, bottom=} in Factorio tile coordinates
-- @return array of { xform = <affine>, reflected = bool }
function M.hats_in_box(box)
  local out = {}
  descend(M.root_shape, root_xform(), M.LEVELS, box, out)
  return out
end

--- World-space polygon for one hat.
function M.hat_polygon(hat)
  local poly = {}
  for i, p in ipairs(HAT_OUTLINE) do
    local x, y = apply(hat.xform, p[1], p[2])
    poly[i] = {x = x, y = y}
  end
  return poly
end

--- Stable identity for a hat, for keying colours, ownership, resources, etc.
-- Quantised so floating-point drift cannot produce two ids for one hat.
function M.hat_id(hat)
  local x, y = apply(hat.xform, 0, 0)
  return string.format("%.3f:%.3f", x, y)
end

--------------------------------------------------------------------------------
-- Rasterisation: which hat covers a given Factorio tile?
--------------------------------------------------------------------------------

local function point_in_polygon(px, py, poly)
  local inside = false
  local n = #poly
  local j = n
  for i = 1, n do
    local a, b = poly[i], poly[j]
    if (a.y > py) ~= (b.y > py) then
      local t = (py - a.y) / (b.y - a.y)
      if px < a.x + t * (b.x - a.x) then inside = not inside end
    end
    j = i
  end
  return inside
end

--- Maps every tile in a chunk to the hat covering its centre.
-- @return table keyed "tx,ty" -> hat
function M.rasterise_chunk(cx, cy)
  local left, top = cx * 32, cy * 32
  local box = {left = left, top = top, right = left + 32, bottom = top + 32}

  local hats = M.hats_in_box(box)
  local polys = {}
  for i, hat in ipairs(hats) do polys[i] = M.hat_polygon(hat) end

  local result = {}
  for ty = top, top + 31 do
    for tx = left, left + 31 do
      local px, py = tx + 0.5, ty + 0.5
      for i = 1, #polys do
        if point_in_polygon(px, py, polys[i]) then
          result[tx .. "," .. ty] = hats[i]
          break
        end
      end
    end
  end
  return result
end

--------------------------------------------------------------------------------
-- Example: cosmetic overlay drawn per chunk.
--
-- Check draw_polygon's current signature against the online API docs -- the
-- rendering API was reworked in 2.0 and returns LuaRenderObject now.
--------------------------------------------------------------------------------

function M.draw_chunk(surface, cx, cy)
  local left, top = cx * 32, cy * 32
  local hats = M.hats_in_box{
    left = left, top = top, right = left + 32, bottom = top + 32,
  }

  for _, hat in ipairs(hats) do
    local poly = M.hat_polygon(hat)
    local verts = {}
    for i, p in ipairs(poly) do verts[i] = {target = p} end

    rendering.draw_polygon{
      surface = surface,
      vertices = verts,
      color = hat.reflected and {0, 0.45, 0.8, 0.5} or {0.55, 0.78, 0.92, 0.35},
      draw_on_ground = true,
    }
  end
end

return M